def _days(a: str, b: str) -> int:
    return (date.fromisoformat(b) - date.fromisoformat(a)).days


def evidence_table() -> dict[str, dict]:
    """id → {lag, confirmed, max_observed, n_samples, note}"""
    out = {}
    for vid, g in VAR.items():
        e = E[g]
        ds = [_days(a, b) for a, b in e["samples"]]
        mx = max(ds)
        lag = mx + e["buffer"]
        confirmed = len(ds) >= 3 and g not in ("HHL",)  # HHL 은 2016년 이후 표본 없음 → 미확인
        if g == "REB":
            confirmed = False  # 표본 2건
        out[vid] = dict(lag=lag, confirmed=confirmed, max_observed=mx, min_observed=min(ds), n_samples=len(ds), group=g,
                        note=f"[lag 검증 2026-11-05] 관측 {len(ds)}건 공개일−기준일 {min(ds)}~{mx}일 → lag {mx}+{e['buffer']}={lag}. 출처: {e['src']}. 수정: {e['rev']}")
    for vid, (lag, conf, why) in RULE.items():
        out[vid] = dict(lag=lag, confirmed=conf, max_observed=None, min_observed=None, n_samples=0, group="rule",
                        note=f"[lag 검증 2026-11-05] {why}")
    return out


